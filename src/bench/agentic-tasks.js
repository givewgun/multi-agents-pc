        '',
        'export function compose(middlewares, finalHandler) {',
        '  return function run(req) {',
        '    let idx = -1;',
        '    function dispatch(i, currentReq) {',
        "      if (i <= idx) throw new Error('next() called multiple times');",
        '      idx = i;',
        '      const fn = i < middlewares.length ? middlewares[i] : finalHandler;',
        '      if (!fn) return undefined;',
        '      return fn(currentReq, (nextReq = currentReq) => dispatch(i + 1, nextReq));',
        '    }',
        '    return dispatch(0, req);',
        '  };',
        '}',
        '',
        'export function createRateLimiter({',
        '  capacity,',
        '  refillPerSec,',
        '  clock = systemClock,',
        '  groupBy,',
        "  keyBy = (req) => req.clientId ?? 'anonymous',",
        '}) {',
        '  const buckets = new Map();',
        '',
        '  function middleware(req, next) {',
        '    const clientId = keyBy(req);',
        "    const group = groupBy ? groupBy(req) : 'default';",
        '    let clientBuckets = buckets.get(clientId);',
        '    if (!clientBuckets) {',
        '      clientBuckets = new Map();',
        '      buckets.set(clientId, clientBuckets);',
        '    }',
        '    const now = clock.now();',
        '    let bucket = clientBuckets.get(group);',
        '    if (!bucket) {',
        '      bucket = { tokens: capacity, lastMs: now };',
        '      clientBuckets.set(group, bucket);',
        '    } else {',
        '      const elapsedSec = Math.max(0, (now - bucket.lastMs) / 1000);',
        '      bucket.tokens = Math.min(capacity, bucket.tokens + elapsedSec * refillPerSec);',
        '      bucket.lastMs = now;',
        '    }',
        '    if (bucket.tokens >= 1) {',
        '      bucket.tokens -= 1;',
        '      return next(req);',
        '    }',
        '    const retryAfter =',
        '      capacity < 1 || refillPerSec <= 0',
        '        ? null',
        '        : Math.max(1, Math.ceil((1 - bucket.tokens) / refillPerSec));',
        '    return {',
        '      status: 429,',
        "      headers: { 'Retry-After': retryAfter },",
        "      body: { error: 'rate_limited' },",
        '    };',
        '  }',
        '',
        '  middleware.reset = function reset(clientId) {',
        '    if (clientId === undefined) {',
        '      buckets.clear();',
        '    } else {',
        '      buckets.delete(clientId);',
        '    }',
        '  };',
        '',
        '  return middleware;',
        '}',
